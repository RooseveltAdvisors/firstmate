#!/usr/bin/env python3
"""
fm-jev-dentry-guard.py - Jev Multi-Agent VFS Inode & Dentry Slab Cache Bloat Guard (Pattern 71)

Audits Linux kernel VFS directory entry (dentry) and inode slab cache memory.
Detects extreme accumulation of reclaimable dentries and inodes (/proc/sys/fs/dentry-state,
/proc/sys/fs/inode-state, /proc/meminfo) generated by multi-agent git worktrees, node_modules trees,
and ephemeral build artifacts that fragment physical memory and exhaust the buddy allocator.

Invariants:
  - Read-only diagnostics by default. Non-destructive.
  - Fail-open: graceful handling on systems with missing or non-standard /proc sysctls.
  - Fast bounded execution (< 0.05s).
"""

import argparse
import json
import os
import sys
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional, Tuple

DEFAULT_WARN_DENTRY_COUNT = 8000000
DEFAULT_WARN_SLAB_RECLAIMABLE_GB = 15.0
DEFAULT_CRIT_SLAB_RECLAIMABLE_GB = 25.0

DENTRY_STATE_PATH = "/proc/sys/fs/dentry-state"
INODE_STATE_PATH = "/proc/sys/fs/inode-state"
INODE_NR_PATH = "/proc/sys/fs/inode-nr"
MEMINFO_PATH = "/proc/meminfo"
VFS_CACHE_PRESSURE_PATH = "/proc/sys/vm/vfs_cache_pressure"


def parse_dentry_state(path: str = DENTRY_STATE_PATH) -> Dict[str, int]:
    """Parses /proc/sys/fs/dentry-state into structured dentry counts."""
    res = {
        "nr_dentry": 0,
        "nr_unused": 0,
        "age_limit": 0,
        "want_pages": 0,
        "nr_negative": 0,
    }
    if not os.path.exists(path):
        return res

    try:
        with open(path, "r") as f:
            parts = f.read().strip().split()
            if len(parts) >= 2:
                res["nr_dentry"] = int(parts[0])
                res["nr_unused"] = int(parts[1])
            if len(parts) >= 3:
                res["age_limit"] = int(parts[2])
            if len(parts) >= 4:
                res["want_pages"] = int(parts[3])
            if len(parts) >= 5:
                res["nr_negative"] = int(parts[4])
    except Exception:
        pass

    return res


def parse_inode_state(state_path: str = INODE_STATE_PATH, nr_path: str = INODE_NR_PATH) -> Dict[str, int]:
    """Parses /proc/sys/fs/inode-state or /proc/sys/fs/inode-nr into inode counts."""
    res = {"nr_inodes": 0, "nr_free_inodes": 0, "preshrink": 0}
    path_to_use = state_path if os.path.exists(state_path) else nr_path
    if not os.path.exists(path_to_use):
        return res

    try:
        with open(path_to_use, "r") as f:
            parts = f.read().strip().split()
            if len(parts) >= 2:
                res["nr_inodes"] = int(parts[0])
                res["nr_free_inodes"] = int(parts[1])
            if len(parts) >= 3:
                res["preshrink"] = int(parts[2])
    except Exception:
        pass

    return res


def parse_meminfo_slab(path: str = MEMINFO_PATH) -> Dict[str, float]:
    """Extracts Slab, SReclaimable, and SUnreclaim in MB and GB from /proc/meminfo."""
    res = {
        "slab_mb": 0.0,
        "slab_gb": 0.0,
        "reclaimable_mb": 0.0,
        "reclaimable_gb": 0.0,
        "unreclaim_mb": 0.0,
        "unreclaim_gb": 0.0,
    }
    if not os.path.exists(path):
        return res

    try:
        with open(path, "r") as f:
            for line in f:
                parts = line.strip().split()
                if len(parts) >= 2:
                    k = parts[0].rstrip(":")
                    if k in ("Slab", "SReclaimable", "SUnreclaim"):
                        kb = float(parts[1])
                        mb = round(kb / 1024.0, 2)
                        gb = round(kb / (1024.0 * 1024.0), 2)
                        if k == "Slab":
                            res["slab_mb"] = mb
                            res["slab_gb"] = gb
                        elif k == "SReclaimable":
                            res["reclaimable_mb"] = mb
                            res["reclaimable_gb"] = gb
                        elif k == "SUnreclaim":
                            res["unreclaim_mb"] = mb
                            res["unreclaim_gb"] = gb
    except Exception:
        pass

    return res


def read_sysctl_val(path: str, default: int = 100) -> int:
    """Reads integer sysctl."""
    if not os.path.exists(path):
        return default
    try:
        with open(path, "r") as f:
            return int(f.read().strip())
    except Exception:
        return default


def audit_dentry_slab(
    dentry_path: str = DENTRY_STATE_PATH,
    inode_path: str = INODE_STATE_PATH,
    inode_nr_path: str = INODE_NR_PATH,
    meminfo_path: str = MEMINFO_PATH,
    vfs_cache_pressure_path: str = VFS_CACHE_PRESSURE_PATH,
    warn_dentries: int = DEFAULT_WARN_DENTRY_COUNT,
    warn_reclaimable_gb: float = DEFAULT_WARN_SLAB_RECLAIMABLE_GB,
    crit_reclaimable_gb: float = DEFAULT_CRIT_SLAB_RECLAIMABLE_GB,
) -> Dict[str, Any]:
    """Performs full fleet audit of VFS dentry and inode slab cache footprint."""
    dentry = parse_dentry_state(dentry_path)
    inode = parse_inode_state(inode_path, inode_nr_path)
    slab = parse_meminfo_slab(meminfo_path)
    vfs_pressure = read_sysctl_val(vfs_cache_pressure_path, default=100)

    nr_dentry = dentry["nr_dentry"]
    nr_unused = dentry["nr_unused"]
    unused_ratio = (nr_unused / nr_dentry) if nr_dentry > 0 else 0.0

    nr_inodes = inode["nr_inodes"]
    nr_free_inodes = inode["nr_free_inodes"]
    reclaimable_gb = slab["reclaimable_gb"]
    total_slab_gb = slab["slab_gb"]

    status = "HEALTHY"
    recommendation = "Kernel VFS dentry and inode slab cache utilization is nominal."

    if reclaimable_gb >= crit_reclaimable_gb or (nr_dentry >= 15000000 and nr_unused >= 14000000):
        status = "CRITICAL"
        recommendation = (
            f"Severe kernel slab bloat: {reclaimable_gb:.2f} GB reclaimable slab across {nr_dentry:,} dentries "
            f"({unused_ratio*100:.1f}% unused) and {nr_inodes:,} inodes. Physical memory buddy allocator is severely "
            "fragmented. Run slab compaction (sudo sh -c 'echo 2 > /proc/sys/vm/drop_caches') to reclaim slab."
        )
    elif reclaimable_gb >= warn_reclaimable_gb or nr_dentry >= warn_dentries:
        status = "WARNING"
        recommendation = (
            f"Elevated kernel slab cache: {reclaimable_gb:.2f} GB reclaimable slab ({total_slab_gb:.2f} GB total) "
            f"holding {nr_dentry:,} dentries ({unused_ratio*100:.1f}% unused) and {nr_inodes:,} inodes. "
            f"vfs_cache_pressure is {vfs_pressure}. Monitor memory fragmentation."
        )

    return {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "summary": {
            "status": status,
            "healthy": (status == "HEALTHY"),
            "nr_dentries": nr_dentry,
            "nr_unused_dentries": nr_unused,
            "unused_dentry_ratio": round(unused_ratio, 4),
            "nr_negative_dentries": dentry["nr_negative"],
            "nr_inodes": nr_inodes,
            "nr_free_inodes": nr_free_inodes,
            "slab_total_gb": total_slab_gb,
            "slab_reclaimable_gb": reclaimable_gb,
            "slab_unreclaim_gb": slab["unreclaim_gb"],
            "vfs_cache_pressure": vfs_pressure,
            "recommendation": recommendation,
        },
        "dentry_state": dentry,
        "inode_state": inode,
        "meminfo_slab": slab,
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Jev Multi-Agent VFS Inode & Dentry Slab Cache Bloat Guard (Pattern 71)"
    )
    parser.add_argument("--json", action="store_true", help="Output results in JSON format")
    parser.add_argument(
        "--warn-dentries",
        type=int,
        default=DEFAULT_WARN_DENTRY_COUNT,
        help=f"Warn threshold for allocated dentries (default: {DEFAULT_WARN_DENTRY_COUNT})",
    )
    parser.add_argument(
        "--warn-reclaimable-gb",
        type=float,
        default=DEFAULT_WARN_SLAB_RECLAIMABLE_GB,
        help=f"Warn threshold for reclaimable slab memory in GB (default: {DEFAULT_WARN_SLAB_RECLAIMABLE_GB})",
    )
    parser.add_argument(
        "--crit-reclaimable-gb",
        type=float,
        default=DEFAULT_CRIT_SLAB_RECLAIMABLE_GB,
        help=f"Critical threshold for reclaimable slab memory in GB (default: {DEFAULT_CRIT_SLAB_RECLAIMABLE_GB})",
    )

    args = parser.parse_args()

    report = audit_dentry_slab(
        warn_dentries=args.warn_dentries,
        warn_reclaimable_gb=args.warn_reclaimable_gb,
        crit_reclaimable_gb=args.crit_reclaimable_gb,
    )

    if args.json:
        print(json.dumps(report, indent=2))
    else:
        s = report["summary"]
        print(f"[{s['status']}] Jev VFS Inode & Dentry Slab Cache Guard (Pattern 71)")
        print(f"Dentries: {s['nr_dentries']:,} allocated | {s['nr_unused_dentries']:,} unused ({s['unused_dentry_ratio']*100:.1f}%) | Negative: {s['nr_negative_dentries']:,}")
        print(f"Inodes: {s['nr_inodes']:,} allocated | {s['nr_free_inodes']:,} free")
        print(f"Slab Memory: {s['slab_total_gb']} GB total | {s['slab_reclaimable_gb']} GB reclaimable | {s['slab_unreclaim_gb']} GB unreclaimable")
        print(f"VFS Cache Pressure: {s['vfs_cache_pressure']}")
        print(f"Status: {s['status']}")
        print(f"Recommendation: {s['recommendation']}")

    return 0 if report["summary"]["healthy"] else 1


if __name__ == "__main__":
    sys.exit(main())
