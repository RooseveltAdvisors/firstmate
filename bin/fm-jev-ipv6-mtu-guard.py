#!/usr/bin/env python3
"""
bin/fm-jev-ipv6-mtu-guard.py - Host IPv6 Maximum Transmission Unit (MTU) & Packet Too Big Guard (Pattern 267 / Pattern 405)

Audits Linux kernel IPv6 MTU configuration (RFC 8200 §5, RFC 4861 §6.3.4)
and Path MTU Discovery (PMTUD) packet telemetry:
  - conf/*/mtu:
      Interface MTU for IPv6 packets (RFC 8200 §5 mandates MTU >= 1280 octets)
  - conf/*/accept_ra_mtu:
      Apply MTU option from Router Advertisements (0 = ignore, 1 = accept valid RA MTU)
  - /proc/net/snmp6:
      Ip6InTooBigErrors = inbound packets larger than interface MTU
      Icmp6InPktTooBigs = incoming ICMPv6 Type 2 (Packet Too Big / PMTUD notifications)
      Icmp6OutPktTooBigs = outgoing ICMPv6 Type 2 (Packet Too Big generated by host)
      Ip6FragOKs = IPv6 datagrams successfully fragmented
      Ip6FragFails = IPv6 datagrams discarded because fragmentation was needed but disallowed
      Ip6FragCreates = IPv6 fragment fragments generated

Invariants:
  - Interface IPv6 MTU must be >= 1280 (RFC 8200 §5 minimum link MTU floor).
  - accept_ra_mtu must be 0 or 1.
  - Inbound Too Big errors should be zero under nominal network conditions.
  - Passive read-only audit: non-destructive.
  - Fail-open: graceful fallback when sysctl paths or snmp6 are missing or restricted.
  - Fast bounded execution (< 0.03s).
"""

import argparse
import datetime
import json
import os
import sys
from typing import Any, Dict, List

CONF_IPV6_BASE = "/proc/sys/net/ipv6/conf"
PROC_SNMP6 = "/proc/net/snmp6"
MIN_IPV6_MTU = 1280


def read_sysctl_int(path: str, default: int = -1) -> int:
    if not os.path.isfile(path):
        return default
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            content = f.read().strip()
        return int(content.split()[0]) if content else default
    except (ValueError, OSError, IndexError):
        return default


def parse_snmp6_mtu(path: str) -> Dict[str, int]:
    metrics: Dict[str, int] = {
        "Ip6InTooBigErrors": 0,
        "Icmp6InPktTooBigs": 0,
        "Icmp6OutPktTooBigs": 0,
        "Ip6FragOKs": 0,
        "Ip6FragFails": 0,
        "Ip6FragCreates": 0,
    }
    if not os.path.isfile(path):
        return metrics

    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            for line in f:
                parts = line.strip().split()
                if len(parts) >= 2 and parts[0] in metrics:
                    try:
                        metrics[parts[0]] = int(parts[1])
                    except ValueError:
                        pass
    except OSError:
        pass
    return metrics


def audit_ipv6_mtu_guard(
    conf_dir: str = CONF_IPV6_BASE,
    snmp6_path: str = PROC_SNMP6,
    min_mtu: int = MIN_IPV6_MTU,
) -> Dict[str, Any]:
    interfaces: Dict[str, Dict[str, Any]] = {}
    issues: List[str] = []
    status = "HEALTHY"

    if os.path.isdir(conf_dir):
        try:
            for ifname in sorted(os.listdir(conf_dir)):
                iface_path = os.path.join(conf_dir, ifname)
                if os.path.isdir(iface_path):
                    mtu_p = os.path.join(iface_path, "mtu")
                    accept_ra_mtu_p = os.path.join(iface_path, "accept_ra_mtu")

                    if os.path.isfile(mtu_p):
                        mtu_val = read_sysctl_int(mtu_p, -1)
                        accept_ra_mtu_val = read_sysctl_int(accept_ra_mtu_p, -1)

                        if mtu_val > 0 and mtu_val < min_mtu:
                            issues.append(
                                f"Interface {ifname} IPv6 mtu={mtu_val} < RFC 8200 minimum {min_mtu}"
                            )
                            status = "WARNING"

                        if accept_ra_mtu_val not in (-1, 0, 1):
                            issues.append(
                                f"Interface {ifname} accept_ra_mtu={accept_ra_mtu_val} invalid (expected 0 or 1)"
                            )
                            status = "WARNING"

                        interfaces[ifname] = {
                            "mtu": mtu_val,
                            "accept_ra_mtu": accept_ra_mtu_val,
                        }
        except OSError:
            pass

    snmp6_metrics = parse_snmp6_mtu(snmp6_path)
    in_too_big_errors = snmp6_metrics.get("Ip6InTooBigErrors", 0)
    icmp6_in_pkt_too_big = snmp6_metrics.get("Icmp6InPktTooBigs", 0)
    icmp6_out_pkt_too_big = snmp6_metrics.get("Icmp6OutPktTooBigs", 0)
    frag_oks = snmp6_metrics.get("Ip6FragOKs", 0)
    frag_fails = snmp6_metrics.get("Ip6FragFails", 0)
    frag_creates = snmp6_metrics.get("Ip6FragCreates", 0)

    if in_too_big_errors > 0:
        issues.append(f"Inbound IPv6 Too Big errors detected: {in_too_big_errors}")
        status = "WARNING"

    if frag_fails > 0:
        issues.append(f"IPv6 fragmentation failures detected: {frag_fails}")
        status = "WARNING"

    default_mtu = interfaces.get("default", {}).get("mtu", 1280)
    all_mtu = interfaces.get("all", {}).get("mtu", 1280)

    return {
        "pattern": 267,
        "name": "ipv6_mtu",
        "description": "Host IPv6 Maximum Transmission Unit (MTU) & Packet Too Big Guard",
        "status": status,
        "healthy": (status == "HEALTHY"),
        "timestamp": datetime.timezone.utc and datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "interfaces_audited": len(interfaces),
        "default_mtu": default_mtu,
        "all_mtu": all_mtu,
        "in_too_big_errors": in_too_big_errors,
        "icmp6_in_pkt_too_big": icmp6_in_pkt_too_big,
        "icmp6_out_pkt_too_big": icmp6_out_pkt_too_big,
        "frag_oks": frag_oks,
        "frag_fails": frag_fails,
        "frag_creates": frag_creates,
        "interfaces": interfaces,
        "issues": issues,
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Audit Host IPv6 Maximum Transmission Unit (MTU) & Packet Too Big Guard (Pattern 267 / Pattern 405)"
    )
    parser.add_argument("--json", action="store_true", help="Output audit report as JSON")
    parser.add_argument("--conf-dir", default=CONF_IPV6_BASE, help="Path to /proc/sys/net/ipv6/conf directory")
    parser.add_argument("--snmp6-file", default=PROC_SNMP6, help="Path to /proc/net/snmp6")
    parser.add_argument(
        "--min-mtu", type=int, default=MIN_IPV6_MTU, help="Minimum safe IPv6 MTU floor (RFC 8200 default 1280)"
    )

    args = parser.parse_args()

    report = audit_ipv6_mtu_guard(
        conf_dir=args.conf_dir,
        snmp6_path=args.snmp6_file,
        min_mtu=args.min_mtu,
    )

    if args.json:
        print(json.dumps(report, indent=2))
    else:
        print(f"Pattern 267: {report['name']} - Status: {report['status']}")
        print(f"  interfaces_audited: {report['interfaces_audited']}")
        print(f"  default_mtu: {report['default_mtu']}")
        print(f"  all_mtu: {report['all_mtu']}")
        print(f"  in_too_big_errors: {report['in_too_big_errors']}, pmtud: in={report['icmp6_in_pkt_too_big']}, out={report['icmp6_out_pkt_too_big']}")
        print(f"  fragmentation: oks={report['frag_oks']}, fails={report['frag_fails']}, creates={report['frag_creates']}")
        if report["issues"]:
            print("  Issues:")
            for issue in report["issues"]:
                print(f"    - {issue}")
        else:
            print("  Issues: none (nominal)")

    return 0 if report["healthy"] else 1


if __name__ == "__main__":
    sys.exit(main())
