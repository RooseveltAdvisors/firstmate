#!/usr/bin/env python3
"""
fm-jev-gate-resolver.py - Jev No-Mistakes Gate Review Finding Classifier & Resolution Generator

Parses structured review findings generated by the no-mistakes gate pipeline
(nm-*-findings.txt, nm-*-review-findings.txt), classifies findings by severity
and authority, and generates canonical resolution payloads and fm-send commands
for Firstmate and workers.
"""

import argparse
import json
import os
import re
import sys
from pathlib import Path


def parse_findings_file(filepath: Path) -> list[dict]:
    """Parse a no-mistakes findings text file into a list of finding dicts."""
    findings = []
    current_finding = {}
    current_field = None

    try:
        content = filepath.read_text(encoding="utf-8", errors="replace")
    except Exception as exc:
        return [{"id": "PARSE_ERROR", "error": str(exc)}]

    for raw_line in content.splitlines():
        line = raw_line.strip()
        if not line:
            if current_finding and "id" in current_finding:
                findings.append(current_finding)
                current_finding = {}
                current_field = None
            continue

        match = re.match(r"^([a-zA-Z_-]+):\s*(.*)$", line)
        if match:
            field_name, field_val = match.group(1).lower(), match.group(2).strip()
            current_field = field_name
            current_finding[field_name] = field_val
        elif current_field:
            current_finding[current_field] += " " + line

    if current_finding and "id" in current_finding:
        findings.append(current_finding)

    return findings


def classify_finding(finding: dict) -> dict:
    """Classify a finding into actionability categories and determine suggested resolution."""
    fid = finding.get("id", "UNKNOWN")
    severity = finding.get("severity", "warning").lower()
    authority = finding.get("authority", "ask-user").lower()
    desc = finding.get("description", "")
    filepath = finding.get("file", "")

    # Category determination
    desc_lower = desc.lower()
    if authority == "auto-fix" or "auto-fix" in desc_lower or "mechanical" in desc_lower:
        category = "auto_fixable"
        action = "authorize_mechanical_fix"
        summary = "Auto-fixable mechanical finding; safe to authorize directly."
    elif "intent-contradiction" in fid.lower() or "policy" in desc_lower or "captain" in desc_lower:
        category = "captain_policy"
        action = "require_captain_ruling"
        summary = "High-leverage policy or intent contradiction; requires supervisor directive."
    elif severity in ("info", "low") or authority == "pre-authorized":
        category = "pre_authorized"
        action = "pre_authorize_waive"
        summary = "Minor or pre-authorized notice; safe to proceed with standard posture."
    elif "test" in filepath.lower() or "mock" in filepath.lower() or "snapshot" in desc_lower:
        category = "test_hygiene"
        action = "authorize_test_update"
        summary = "Test harness or snapshot update required to reflect intentional code changes."
    else:
        category = "triage_needed"
        action = "review_and_resolve"
        summary = "General review finding requiring engineering judgment."

    resolution_text = (
        f"AUTHORIZED RESOLUTION (Jev System One): For finding {fid} ({category}) in {filepath}: "
        f"{summary} Action: {action}."
    )

    return {
        "id": fid,
        "severity": severity,
        "authority": authority,
        "file": filepath,
        "line": finding.get("line", ""),
        "category": category,
        "action": action,
        "summary": summary,
        "resolution_text": resolution_text,
    }


def main():
    parser = argparse.ArgumentParser(
        description="Jev No-Mistakes Gate Review Finding Classifier & Resolution Generator"
    )
    parser.add_argument("findings_file", nargs="?", default="", help="Path to nm-*-findings.txt file")
    parser.add_argument("--json", action="store_true", help="Output telemetry in JSON format")
    parser.add_argument("--resolve-cmds", action="store_true", help="Generate ready-to-run fm-send resolution commands")
    parser.add_argument("--child", default="worker", help="Target child name for fm-send command generation")
    parser.add_argument("--key", default="", help="Resolve key (defaults to filename-based key)")
    args = parser.parse_args()

    findings_file = Path(args.findings_file) if args.findings_file else None

    # If no file specified, search for recent findings in /opt/ra/firstmate/data
    if not findings_file or not findings_file.is_file():
        data_dir = Path(os.environ.get("FM_DATA_OVERRIDE", "/opt/ra/firstmate/data"))
        candidate_files = sorted(
            data_dir.glob("**/nm-*-findings.txt"),
            key=lambda p: p.stat().st_mtime if p.exists() else 0,
            reverse=True,
        )
        if candidate_files:
            findings_file = candidate_files[0]

    if not findings_file or not findings_file.is_file():
        res = {
            "status": "HEALTHY",
            "summary": "No active no-mistakes findings files detected in workspace",
            "findings_count": 0,
            "findings": [],
        }
        if args.json:
            print(json.dumps(res, indent=2))
        else:
            print("[fm-jev-gate-resolver] No active no-mistakes findings files detected (HEALTHY)")
        sys.exit(0)

    raw_findings = parse_findings_file(findings_file)
    classified = [classify_finding(f) for f in raw_findings]

    # Resolve key deduction
    resolve_key = args.key
    if not resolve_key:
        match = re.search(r"(nm-[0-9A-Z]+)", findings_file.name)
        resolve_key = f"{match.group(1)}-review" if match else f"gate-review-{findings_file.stem}"

    # Generate commands
    resolve_cmds = []
    for c in classified:
        cmd = f'bin/fm-send.sh --delivery follow-up --resolve-key {resolve_key} {args.child} "{c["resolution_text"]}"'
        c["cmd"] = cmd
        resolve_cmds.append(cmd)

    counts = {
        "auto_fixable": sum(1 for c in classified if c["category"] == "auto_fixable"),
        "captain_policy": sum(1 for c in classified if c["category"] == "captain_policy"),
        "pre_authorized": sum(1 for c in classified if c["category"] == "pre_authorized"),
        "test_hygiene": sum(1 for c in classified if c["category"] == "test_hygiene"),
        "triage_needed": sum(1 for c in classified if c["category"] == "triage_needed"),
    }

    status = "WARNING" if counts["captain_policy"] > 0 else "HEALTHY"
    summary_text = (
        f"Parsed {len(classified)} findings from {findings_file.name}: "
        f"{counts['auto_fixable']} auto-fix, {counts['pre_authorized']} pre-auth, "
        f"{counts['test_hygiene']} test-hygiene, {counts['captain_policy']} policy ({status})"
    )

    output = {
        "status": status,
        "summary": summary_text,
        "file": str(findings_file),
        "resolve_key": resolve_key,
        "counts": counts,
        "findings": classified,
        "resolve_cmds": resolve_cmds if args.resolve_cmds else [],
    }

    if args.json:
        print(json.dumps(output, indent=2))
    else:
        print(f"[fm-jev-gate-resolver] {summary_text}")
        for c in classified:
            print(f"  * [{c['id']}] {c['severity']} ({c['category']}) in {c['file']}:{c['line']}: {c['summary']}")
        if args.resolve_cmds:
            print("\nGenerated resolution commands:")
            for cmd in resolve_cmds:
                print(f"  {cmd}")

    sys.exit(0 if status == "HEALTHY" else 1)


if __name__ == "__main__":
    main()
